#!/usr/bin/env node
/**
 * Writes gitignored src/environments/version.ts from the current git commit
 * (or GITHUB_* env when present). Run via npm prestart / prebuild / postinstall —
 * do not commit the output or push it from CI.
 *
 * Stores an ISO instant; the UI formats it in the viewer's local timezone.
 */
import { execSync } from 'node:child_process';
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outPath = join(root, 'src', 'environments', 'version.ts');

function git(cmd) {
  try {
    return execSync(cmd, { cwd: root, encoding: 'utf8' }).trim();
  } catch {
    return '';
  }
}

function pad(n) {
  return String(n).padStart(2, '0');
}

/** Local wall time for build-log preview only. */
function formatLocalStamp(date) {
  return `${date.getFullYear()}-${pad(date.getMonth() + 1)}-${pad(date.getDate())} ${pad(date.getHours())}:${pad(date.getMinutes())}`;
}

function committedAtIso(sha) {
  const iso = (
    (sha && sha !== 'unknown' ? git(`git log -1 --format=%cI ${sha}`) : '') ||
    git('git log -1 --format=%cI')
  ).trim();
  if (iso) {
    const d = new Date(iso);
    if (!Number.isNaN(d.getTime())) return d.toISOString();
  }
  return new Date().toISOString();
}

const shaFull = (process.env.GITHUB_SHA || git('git rev-parse HEAD') || 'unknown').trim();
const sha = shaFull.length >= 7 ? shaFull.slice(0, 7) : shaFull;
const branch = (
  process.env.GITHUB_HEAD_REF ||
  process.env.GITHUB_REF_NAME ||
  git('git rev-parse --abbrev-ref HEAD') ||
  'unknown'
).trim();
const committedAt = committedAtIso(shaFull);

const source = `/* Auto-generated by scripts/write-git-version.mjs - do not edit. */
export const appVersion = {
  /** Commit time as UTC ISO; format to local timezone in the UI. */
  committedAt: ${JSON.stringify(committedAt)},
  sha: ${JSON.stringify(sha)},
  branch: ${JSON.stringify(branch)},
} as const;
`;

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, source, 'utf8');
console.log(`[write-git-version] ${formatLocalStamp(new Date(committedAt))} ${sha} ${branch}`);
